#!/usr/bin/env python3
"""Static ARM7 block translator for the AICA sound driver (MANATEE.DRV).

Each block is a straight run of instructions starting at a leader (a PC reached by a control transfer, recorded
by a desktop run with DB_ARMLEADERS, plus the exception vectors). A block is emitted as calls to the
interpreter's own always-inline exec(op, pc) with constant arguments, so GCC folds the decoding away while the
semantics stay identical to the interpreter (host/arm7.cpp). The interpreter remains the fallback for any PC
without a block, for blocks that do not fit the remaining sample budget, and whenever the code in ARAM no
longer matches the translated image.

usage: arm7rec.py DRIVER LEADERS OUT.inc
"""
import struct, sys

CODE_OFF, CODE_LEN = 0x20, 0x9040      # driver code: file bytes 0x20.. (after the SDRV header), loaded at ARAM 0
MAX_BLOCK = 48

def is_terminator(op):
    """True if the instruction may change control flow, mode or interrupt masks: the block ends after it."""
    cls = (op >> 25) & 7
    if (op >> 28) == 0xF:
        return True                                    # NV space: let the interpreter handle it
    if cls == 5:
        return True                                    # B/BL
    if cls in (6, 7):
        return True                                    # coprocessor / SWI / undefined
    if cls == 4:                                       # LDM/STM
        L, S, lst = (op >> 20) & 1, (op >> 22) & 1, op & 0xFFFF
        return bool(S) or (L and (lst & 0x8000))
    if cls in (2, 3):                                  # LDR/STR
        L, P, W = (op >> 20) & 1, (op >> 24) & 1, (op >> 21) & 1
        rd, rn = (op >> 12) & 15, (op >> 16) & 15
        if L and rd == 15:
            return True
        if rn == 15 and (W or not P):
            return True
        return False
    # cls 0/1
    if cls == 0 and (op & 0x0FFFFFF0) == 0x012FFF10:
        return True                                    # BX
    if cls == 0 and (op & 0x90) == 0x90 and (op & 0x60):   # halfword transfers
        L, rd = (op >> 20) & 1, (op >> 12) & 15
        return bool(L and rd == 15)
    if cls == 0 and (op & 0x0FC000F0) == 0x00000090:   # MUL/MLA
        return ((op >> 16) & 15) == 15
    if cls == 0 and (op & 0x0F8000F0) == 0x00800090:   # long multiply
        return ((op >> 16) & 15) == 15 or ((op >> 12) & 15) == 15
    if cls == 0 and (op & 0x0FB00FF0) == 0x01000090:   # SWP
        return ((op >> 12) & 15) == 15
    opc, S = (op >> 21) & 15, (op >> 20) & 1
    if not S and 8 <= opc <= 11:
        return bool(op & (1 << 21))                    # MSR ends the block (I/F bits, mode); MRS does not
    rd = (op >> 12) & 15
    if rd == 15 and not (8 <= opc <= 11):
        return True                                    # data processing writing the PC
    return False

def is_store(op):
    cls = (op >> 25) & 7
    if cls in (2, 3):
        return not ((op >> 20) & 1)
    if cls == 4:
        return not ((op >> 20) & 1)
    if cls == 0 and (op & 0x90) == 0x90 and (op & 0x60):
        return not ((op >> 20) & 1)
    if cls == 0 and (op & 0x0FB00FF0) == 0x01000090:
        return True                                    # SWP
    return False

def main():
    drv, leaders_path, out_path = sys.argv[1:4]
    img = open(drv, "rb").read()[CODE_OFF:CODE_OFF + CODE_LEN]
    words = [struct.unpack_from("<I", img, a)[0] for a in range(0, CODE_LEN, 4)]
    leaders = {0x00, 0x04, 0x08, 0x0C, 0x10, 0x14, 0x18, 0x1C}
    for line in open(leaders_path):
        a = int(line.split()[0], 16)
        if a < CODE_LEN and a % 4 == 0:
            leaders.add(a)
    used = set()
    out = []
    out.append("// Generated by tools/arm7rec.py from MANATEE.DRV - do not edit.")
    out.append("// %d blocks; each returns the number of instructions it executed." % len(leaders))
    out.append("static constexpr uint32_t kCodeEnd = 0x%x;" % CODE_LEN)
    table = []
    for lead in sorted(leaders):
        body = []
        a, n = lead, 0
        while a < CODE_LEN and n < MAX_BLOCK:
            op = words[a // 4]
            used.add(a)
            n += 1
            body.append("    r[15] = 0x%xu; instr_count++; exec(0x%08xu, 0x%xu);" % (a + 4, op, a))
            if is_terminator(op):
                break
            if is_store(op):
                body.append("    if (fiq_line && !(cpsr & 0x40)) return %d;" % n)
            a += 4
        out.append("static int blk_%05x() {" % lead)
        out += body
        out.append("    return %d;" % n)
        out.append("}")
        table.append((lead, n))
    out.append("struct ArmBlock { int (*fn)(); uint8_t len; };")
    out.append("static const ArmBlock kBlocks[kCodeEnd / 4] = {")
    idx = {a: (a, n) for a, n in table}
    rows = []
    for a in range(0, CODE_LEN, 4):
        if a in idx:
            rows.append("    {blk_%05x, %d}," % (a, idx[a][1]))
        else:
            rows.append("    {nullptr, 0},")
    out += rows
    out.append("};")
    # translated instruction words: validated against ARAM, and ARM-side stores to them disable the blocks
    out.append("static const uint32_t kUsedCount = %d;" % len(used))
    out.append("static const uint32_t kUsed[][2] = {")
    for a in sorted(used):
        out.append("    {0x%x, 0x%08xu}," % (a, words[a // 4]))
    out.append("};")
    open(out_path, "w").write("\n".join(out) + "\n")
    print("blocks %d, translated instructions %d (unique addresses %d)" % (len(table), sum(n for _, n in table), len(used)))

if __name__ == "__main__":
    main()
